import { api } from "../../lib/api.js";
import { knowTitle } from "../../lib/artifact.js";
import { audienceBadge, emptyCard, filterMenu, formats, kindOptions, kinds, nameCell, producer, search, updated } from "../../lib/artifacts.js";
import { h } from "../../lib/dom.js";
import { icon } from "../../lib/icons.js";
import { compose } from "../../lib/pane.js";
import { go } from "../../lib/router.js";

// nav makes Artifacts one of a repository's tabs, before its Settings.
export const nav = { label: "Artifacts", order: 70 };
export const accepts = (rest) => !rest.length;
export const crumbs = ({ root }) => [{ label: "Artifacts", href: root + "/artifacts" }];

// accesses are the Access filter's options: an artifact's widest audience.
const accesses = [{ value: "", word: "Any access" }, { value: "organization", word: "Organization" }, { value: "repository", word: "Repository" },
  { value: "private", word: "Only you, or shared with you" }];

// The artifacts attached to the repository (Figma "Repository · Artifacts") that the viewer may list or read, newest
// change first, filtered by kind through the API and by access and title as chosen; a viewer who may ask the
// organization's agents asks one for another in the repository's conversation.
export default async ({ org, repo, path, orgCan }) => {
  const query = new URLSearchParams(location.search);
  const list = (await api("GET", path + "/artifacts" + (query.get("kind") ? "?" + new URLSearchParams({ kind: query.get("kind") }) : ""))).artifacts;
  list.forEach(knowTitle);
  const kind = kinds[query.get("kind")];
  const ask = orgCan("agents.assign") ? h("button", { class: "btn btn-primary", type: "button",
    onclick: () => compose("Write a " + (kind ? kind.word.toLowerCase() : "document") + " about ", true) }, icon("sparkles"), "Ask an agent for one") : null;
  if (!list.length && !query.size) {
    return [emptyCard("No artifacts yet", "Ask an agent for a document, a diagram, a report or a page about this repository, and it shows here.", ask)];
  }
  const refilter = (q) => go("/" + org.slug + "/" + repo.slug + "/artifacts" + (q.size ? "?" + q : ""), true);
  const tbody = h("tbody", {});
  const none = h("p", { class: "cell-muted", hidden: true }, "No artifact matches.");
  const access = query.get("access");
  const filter = search("Filter artifacts", () => draw());
  const table = h("table", { class: "table" }, h("thead", {}, h("tr", {}, ["Artifact", "Kind", "Generated by", "Access", "Updated"].map((t) => h("th", {}, t)))), tbody);
  const rows = new Map(list.map((a) => [a, h("tr", {}, nameCell(org, a, kinds[a.kind].icon, a.summary || formats[a.mediaType] || ""),
    h("td", {}, h("span", { class: "tag" }, kinds[a.kind].word)), h("td", {}, producer(a)), h("td", {}, audienceBadge(a)),
    h("td", { class: "cell-muted" }, a.updatedAt ? updated(a.updatedAt) : ""))]));
  const draw = () => {
    const shown = list.filter((a) => (!access || a.audience === access) && filter.matches(a));
    tbody.replaceChildren(...shown.map((a) => rows.get(a)));
    table.hidden = !shown.length;
    none.hidden = !!shown.length;
  };
  draw();
  return [h("div", { class: "filters" }, filter.el, h("span", { class: "artifact-spacer" }),
    filterMenu("kind", null, "Kind", kindOptions("Any kind"), refilter), filterMenu("access", null, "Access", accesses, refilter), ask), table, none];
};
