// Artifacts as the Console draws them on the organization's Artifacts page, a repository's Artifacts tab and an
// artifact's own page (pages/org/artifacts.js, pages/repo/artifacts.js): their kinds, formats and audiences as the
// design system names them, the cells of their tables, and the menus that filter those.

import { h } from "./dom.js";
import { avatar, icon } from "./icons.js";
import { popover } from "./menu.js";
import { base, me } from "./state.js";

// kinds are what an artifact is for, each with its word and the icon its row leads with (Figma "Repository ·
// Artifacts").
export const kinds = {
  document: { word: "Document", icon: "file" },
  diagram: { word: "Diagram", icon: "git-fork" },
  report: { word: "Report", icon: "activity" },
  page: { word: "Page", icon: "globe" },
};

// formats name the media types a version is written in.
export const formats = { "text/markdown": "Markdown", "image/svg+xml": "SVG", "text/html": "HTML" };

// audiences are an artifact's widest audience as its list's Access column says it, a quiet badge: the organization's
// readers, its repository's, or nobody past those it is shared with, which is "Only you" to its owner.
export const audiences = {
  organization: { word: "Organization", tone: "success" },
  repository: { word: "Repository", tone: "info" },
  private: { word: "Shared with you", tone: "neutral" },
};

// listedOnly is whether the viewer may list an artifact but not open it: such an item holds only its ID, title, kind
// and owner.
export const listedOnly = (a) => !a.permissions || !a.permissions.includes("artifacts.read");

// artifactHref is the Console's page of an artifact, at its version n when given.
export const artifactHref = (org, a, n) => base + org.slug + "/artifacts/" + a.id + (n ? "?version=" + n : "");

// audienceBadge is an artifact's widest audience as a quiet badge.
export function audienceBadge(a) {
  if (listedOnly(a)) return h("span", { class: "badge-quiet tone-neutral", title: "You may see that it exists, not open it" }, "Listed");
  const s = a.audience === "private" && a.owner && a.owner.id === me.id ? { word: "Only you", tone: "neutral" } : audiences[a.audience] || audiences.private;
  return h("span", { class: "badge-quiet tone-" + s.tone }, s.word);
}

// updated is how long ago a moment was, as a list of artifacts says it: 14 minutes ago, yesterday, last week.
export function updated(at) {
  const words = new Intl.RelativeTimeFormat(undefined, { numeric: "auto" });
  const seconds = (new Date(at).getTime() - Date.now()) / 1000;
  const units = [[60, "second"], [60, "minute"], [24, "hour"], [7, "day"], [4.35, "week"], [12, "month"]];
  let n = seconds;
  for (const [size, unit] of units) {
    if (Math.abs(n) < size) return unit === "second" ? "just now" : words.format(Math.round(n), unit);
    n /= size;
  }
  return words.format(Math.round(n), "year");
}

// whence is where an agent wrote an artifact: its task's number and the branch it came from, such as "#16 on
// feature/push-worker"; empty when it names neither.
export const whence = (a) => [a.taskNumber ? "#" + a.taskNumber : null, a.branch ? "on " + a.branch : null].filter(Boolean).join(" ");

// producer is who wrote an artifact, as its row's Generated by says it: the agent, or the person, with their avatar,
// over where it was written; for one the viewer may only list, whose writer it doesn't hold, its owner.
export function producer(a) {
  const by = a.agent || a.createdBy || (listedOnly(a) ? a.owner : null);
  if (!by) return h("span", { class: "cell-muted" }, listedOnly(a) ? "" : "Someone since gone");
  return h("div", { class: "cell-person" }, avatar(by.displayName, !!a.agent),
    h("div", { class: "cell-two-lines artifact-by" }, h("span", {}, by.displayName), whence(a) ? h("span", {}, whence(a)) : null));
}

// nameCell is an artifact's row's first cell: the icon it leads with, its title, which opens it unless the viewer may
// only list it, and the line under it.
export function nameCell(org, a, glyph, under) {
  const title = listedOnly(a) ? h("span", {}, a.title) : h("a", { href: artifactHref(org, a), "data-nav": "" }, a.title);
  return h("td", { class: "cell-two-lines" }, h("div", { class: "artifact-name" }, icon(glyph),
    h("div", { class: "cell-two-lines" }, title, h("span", {}, listedOnly(a) ? "Shared for listing only" : under))));
}

// choice is one of a filter menu's items: its word, checked when it is the one chosen.
const choice = (word, checked, pick, lead = null) => h("button", { class: "menu-item", type: "button", role: "menuitemradio", "aria-checked": String(checked), onclick: pick },
  lead, h("span", {}, word));

// filterMenu is a filter of a list as a button, led by glyph's icon when given, that opens a menu of its options
// ({ value, word, lead }), the one the page's query names under name checked: the button says label until one is
// chosen, then the option's word, and picking one opens the list again at go(query).
export function filterMenu(name, glyph, label, options, go) {
  const query = new URLSearchParams(location.search);
  const current = query.get(name) || "";
  const chosen = options.find((o) => o.value === current);
  const button = h("button", { class: "btn", type: "button", "aria-haspopup": "menu" }, glyph ? icon(glyph) : null, h("span", {}, chosen && current ? chosen.word : label), icon("chevron-down"));
  button.addEventListener("click", () => popover(button, "start", (close) => options.map((o) => o.divider ? h("hr", { class: "menu-divider" })
    : choice(o.word, o.value === current, () => {
      close();
      if (o.value) query.set(name, o.value);
      else query.delete(name);
      go(query);
    }, o.lead))));
  return button;
}

// kindOptions are the kinds as a filter's options, after any kind.
export const kindOptions = (any) => [{ value: "", word: any }, ...Object.entries(kinds).map(([value, k]) => ({ value, word: k.word, lead: icon(k.icon) }))];

// search is a list's filter by title and summary, as B's Input with its search icon, which calls draw on each change.
export function search(placeholder, draw) {
  const input = h("input", { type: "search", placeholder, "aria-label": placeholder, oninput: () => draw() });
  return { el: h("div", { class: "input" }, icon("search"), input), matches: (a) => {
    const q = input.value.trim().toLowerCase();
    return !q || [a.title, a.summary || ""].some((t) => t.toLowerCase().includes(q));
  } };
}

// emptyCard is B's Empty state in a card: a list with nothing in it, what would fill it, and the action that does.
export const emptyCard = (title, description, action) => h("div", { class: "card" }, h("div", { class: "empty" }, h("div", { class: "empty-icon" }, icon("file")),
  h("h2", { class: "empty-title" }, title), h("p", { class: "empty-description" }, description), action || null));
