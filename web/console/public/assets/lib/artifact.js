// titles are the titles of the artifacts this browser read, by ID, which the breadcrumbs name before the page reads
// its artifact again.
const titles = new Map();
export const titleOf = (id) => titles.get(id) || "Artifact";
export const knowTitle = (a) => titles.set(a.id, a.title);

// reading is the read of the artifact the page shows, which its subject starts and its body takes, so the two make
// one call: { key, read }.
let reading = null;

// read reads one of the organization's artifacts, or takes the read the page's subject started.
function read(org, id) {
  const key = org.slug + "/" + id;
  const taken = reading && reading.key === key ? reading.read : null;
  reading = null;
  return taken || api("GET", "/orgs/" + org.slug + "/artifacts/" + encodeURIComponent(id));
}

// artifactSubject is the conversation the pane shows on an artifact's page: the viewer's own about its repository,
// where they ask an agent to revise it, or about its organization for one attached to none.
export function artifactSubject(org, can, id) {
  const r = api("GET", "/orgs/" + org.slug + "/artifacts/" + encodeURIComponent(id));
  reading = { key: org.slug + "/" + id, read: r };
  return r.then((a) => (a.repository ? privateSubject("repo:" + org.slug + "/" + a.repository.slug, a.repository.slug, true,
    "/orgs/" + org.slug + "/repos/" + a.repository.slug + "/conversation", can) : null), () => null);
}

// reaches say how far an audience reaches an artifact: as its header's badge, its Access card and Share say it.
const reaches = { view: "can view", edit: "can edit" };
const reachRoles = { view: "View", edit: "Edit" };
const reachWords = { none: "No access", view: "Can view", edit: "Can edit" };

// roles are the roles an artifact grants, as its Access card names them.
const roles = { owner: "Owner", editor: "Editor", viewer: "Viewer", lister: "Lister" };

// reachBadge is an artifact's widest audience as a quiet badge: its organization's, its repository's, or nobody past
// those it is shared with.
function reachBadge(a) {
  if (a.organizationAccess && a.organizationAccess !== "none") return h("span", { class: "badge-quiet tone-success" }, "Organization " + reaches[a.organizationAccess]);
  if (a.repositoryAccess && a.repositoryAccess !== "none") return h("span", { class: "badge-quiet tone-info" }, "Repository " + reaches[a.repositoryAccess]);
  return h("span", { class: "badge-quiet tone-neutral" }, a.audience === "private" && a.permissions.includes("artifacts.manage") ? "Only you" : "Shared with you");
}

// origin is the line under an artifact's title: who wrote it and from where, the version shown and its last change.
function origin(a, n) {
  const by = a.agent ? "Generated by " + a.agent.displayName : a.createdBy ? "Written by " + a.createdBy.displayName : "";
  const where = [a.taskNumber ? "from task #" + a.taskNumber : "", a.branch ? "on " + a.branch : ""].filter(Boolean).join(" ");
  const version = n && n !== a.head ? "version " + n + " of " + a.head : "version " + a.head;
  const change = a.updatedAt ? "updated " + updated(a.updatedAt) + (a.updatedBy ? " by " + a.updatedBy.displayName : "") : "";
  return [[by, where].filter(Boolean).join(" "), version, change].filter(Boolean).join(" · ");
}

// pathOf is the Console's path of an artifact's page, which go takes.
const pathOf = (org, a) => "/" + org.slug + "/artifacts/" + a.id;

// rawHref is the REST API's link to a version's body, which serves it sandboxed, as an attachment when download is set.
const rawHref = (org, a, n, download) => config.restUrl + "/v1/orgs/" + org.slug + "/artifacts/" + a.id + "/versions/" + n + "/raw" + (download ? "?download=true" : "");

// body is a version as the page shows it, none of it running in the Console's origin: Markdown as the API rendered and
// sanitized it, in a frame that runs nothing; an SVG as an image; an HTML page in a sandboxed frame, which the API also
// serves under a policy that runs nothing and calls nowhere.
function body(org, a, v) {
  if (v.mediaType === "text/markdown") return h("div", { class: "card card-body artifact-document" }, rendered(v.html || ""));
  if (v.mediaType === "image/svg+xml") return h("div", { class: "card card-body artifact-image" }, h("img", { src: rawHref(org, a, v.number), alt: a.title }));
  return h("div", { class: "card artifact-page" }, h("iframe", { class: "artifact-frame", sandbox: "", src: rawHref(org, a, v.number), title: a.title }));
}

// fact is one of the About card's rows: its name, muted, and its value.
const fact = (name, value) => h("tr", {}, h("td", { class: "cell-muted" }, name), h("td", {}, value));

// agentOf is whether a principal an artifact names is an agent: the one that wrote it, or one of the organization's.
const agentOf = (a, p) => !!p && ((a.agent && a.agent.id === p.id) || agents.has(p.id));

// by is a principal as a fact names it: their avatar and their name.
const by = (a, p) => h("div", { class: "cell-person" }, avatar(p.displayName, agentOf(a, p)), h("span", {}, p.displayName));

// about is the About card: the artifact's repository, kind, who wrote it, from which task and branch, and when.
function about(a) {
  const from = a.taskNumber ? fact("From task", h("code", { class: "cell-mono" }, ["#" + a.taskNumber, a.branch].filter(Boolean).join(" · ")))
    : a.branch ? fact("Branch", h("code", { class: "cell-mono" }, a.branch)) : null;
  return h("section", { class: "card" }, h("header", { class: "card-header" }, h("h2", { class: "card-title" }, "About")),
    h("table", { class: "table facts" }, h("tbody", {},
      fact("Repository", a.repository ? h("code", { class: "cell-mono" }, a.repository.slug) : h("span", { class: "cell-muted" }, "None")),
      fact("Kind", kinds[a.kind].word),
      a.agent || a.createdBy ? fact(a.agent ? "Generated by" : "Written by", by(a, a.agent || a.createdBy)) : null,
      from,
      a.createdAt ? fact("Created", when(a.createdAt)) : null)));
}

// row is one of the Access and Versions cards' rows: what leads it, its text, and what follows.
const row = (lead, text, ...after) => h("div", { class: "card-row" }, lead, h("div", { class: "row-text" }, text), ...after);

// access is the Access card: the artifact's owner and those it is shared with, each with their role, which a viewer who
// manages it takes back; then how far its repository's and its organization's readers reach it; Manage opens Share.
function access(org, a, who, manage, share, refresh) {
  const person = (p, agent, role, unshare) => row(avatar(p.displayName, agent, 24), h("span", { class: "row-title" }, p.displayName),
    h("span", { class: "row-aside" }, role),
    unshare ? h("button", { class: "icon-btn icon-btn-ghost icon-btn-sm", type: "button", "aria-label": "Stop sharing with " + p.displayName,
      title: "Stop sharing", onclick: unshare }, icon("x")) : null);
  const unshare = (g) => () => api("DELETE", "/orgs/" + org.slug + "/artifacts/" + a.id + "/access/" + g.principalId).then(refresh, refresh);
  const grants = who.grants.filter((g) => !a.owner || g.principalId !== a.owner.id)
    .map((g) => person(g, g.kind === "agent", roles[g.role], manage ? unshare(g) : null));
  const audience = (label, reach, glyph) => reach && reach !== "none"
    ? row(h("span", { class: "avatar avatar-24 avatar-machine", "aria-hidden": "true" }, icon(glyph)), h("span", { class: "row-title" }, label),
      h("span", { class: "row-aside" }, reachRoles[reach])) : null;
  const audiences = [a.repository ? audience(a.repository.slug + " · repository", who.repositoryAccess, "folder-git-2") : null,
    audience(org.name + " · organization", who.organizationAccess, "users")].filter(Boolean);
  return h("section", { class: "card" }, h("header", { class: "card-header" }, h("h2", { class: "card-title" }, "Access"),
    manage ? h("button", { class: "btn btn-ghost btn-sm", type: "button", onclick: share }, "Manage") : null),
  a.owner ? person(a.owner, agentOf(a, a.owner), "Owner") : null, ...grants,
  row(null, h("span", { class: "row-meta" }, "Audiences")),
  ...(audiences.length ? audiences : [row(null, h("span", { class: "row-meta" }, "Nobody else reaches it"))]));
}

// versions is the Versions card: the artifact's versions, newest first, each with why it was written, by whom and when,
// opening it; the one shown is current.
function versions(org, a, list, n) {
  return h("section", { class: "card" }, h("header", { class: "card-header" }, h("h2", { class: "card-title" }, "Versions"),
    h("span", { class: "card-meta" }, String(list.length))),
  ...list.map((v) => h("a", { class: "card-row artifact-version", href: artifactHref(org, a, v.number === a.head ? 0 : v.number), "data-nav": "",
    "aria-current": v.number === n ? "true" : null },
  h("span", { class: "row-mono" }, "v" + v.number), v.author ? avatar(v.author.displayName, agentOf(a, v.author)) : null,
  h("div", { class: "row-text" }, h("span", { class: "row-title" }, v.note || "Version " + v.number),
    h("span", { class: "row-meta" }, [v.author ? v.author.displayName : "", updated(v.createdAt)].filter(Boolean).join(" · "))))));
}

// shareDialog is Share: how far the artifact's repository's and organization's readers reach it, and a member, an
// API key or an agent to give a role on it; saving changes what changed, from the version shown.
function shareDialog(org, a, who, people, refresh) {
  const reach = (name, value) => h("select", { name }, Object.entries(reachWords).map(([v, w]) => h("option", { value: v, selected: v === value }, w)));
  const repo = a.repository ? reach("repositoryAccess", who.repositoryAccess) : null;
  const orgReach = reach("organizationAccess", who.organizationAccess);
  const principal = h("select", { name: "principalId" }, h("option", { value: "" }, "Nobody"),
    people.map((p) => h("option", { value: p.id }, p.name + (p.agent ? " (agent)" : ""))));
  const role = h("select", { name: "role" }, ["viewer", "editor", "owner"].map((r) => h("option", { value: r }, roles[r])));
  openDialog({
    title: "Share " + a.title,
    body: [repo ? field("Readers of " + a.repository.slug, selectBox(repo), "Everyone who reads the repository.") : null,
      field("Members of " + org.name, selectBox(orgReach), "Everyone who reads the organization."),
      field("Share with", selectBox(principal), "A member or an agent, in place of any role they hold on it."), field("As", selectBox(role))],
    action: "Save",
    submit: async () => {
      const patch = {};
      if (repo && repo.value !== who.repositoryAccess) patch.repositoryAccess = repo.value;
      if (orgReach.value !== who.organizationAccess) patch.organizationAccess = orgReach.value;
      if (Object.keys(patch).length) {
        await api("PATCH", "/orgs/" + org.slug + "/artifacts/" + a.id, patch, { "Content-Type": "application/merge-patch+json", "If-Match": '"' + a.version + '"' })
          .catch((err) => Promise.reject(err.status === 412 ? new Error("Someone changed it meanwhile. Close this and open Share again.") : err));
      }
      if (principal.value) await api("POST", "/orgs/" + org.slug + "/artifacts/" + a.id + "/access", { principalId: principal.value, role: role.value });
      refresh();
    },
  });
}

// editDialog is Edit: the artifact's title and the version shown's body, which saving writes as its next version, with
// why, from the artifact as the page shows it.
function editDialog(org, a, v, refresh) {
  const title = input({ name: "title", required: true, maxlength: 200, value: a.title });
  const text = textarea({ name: "body", required: true, rows: 18, spellcheck: "false" });
  text.value = v.body || "";
  const note = input({ name: "note", maxlength: 500, placeholder: "What changed" });
  const path = "/orgs/" + org.slug + "/artifacts/" + a.id;
  const changed = (err) => Promise.reject(err.status === 412 ? new Error("Someone changed it meanwhile. Close this to see their change, then edit it again.") : err);
  openDialog({
    title: "Edit " + a.title,
    body: [field("Title", title), field(formats[v.mediaType] || "Body", text, "Saving writes it as version " + (a.head + 1) + "."), field("Why", note)],
    action: "Save",
    submit: async () => {
      let tag = '"' + a.version + '"';
      if (title.value !== a.title) {
        const after = await api("PATCH", path, { title: title.value }, { "Content-Type": "application/merge-patch+json", "If-Match": tag }).catch(changed);
        tag = '"' + after.version + '"';
      }
      if (text.value !== v.body || v.number !== a.head) {
        await api("POST", path + "/versions", { id: crypto.randomUUID(), mediaType: v.mediaType, body: text.value, note: note.value }, { "If-Match": tag }).catch(changed);
      }
      refresh(true);
    },
  });
}

// people are the organization's members and agents, which Share offers, by name.
const people = (org) => Promise.all([api("GET", "/orgs/" + org.slug + "/members").then((d) => d.members, () => []),
  api("GET", "/orgs/" + org.slug + "/agents").then((d) => d.agents, () => [])])
  .then(([members, agents]) => [...members.map((m) => ({ id: m.userId, name: m.displayName })), ...agents.map((g) => ({ id: g.id, name: g.name, agent: true }))]
    .sort((x, y) => x.name.localeCompare(y.name)));

// gone is the page of an artifact that isn't there, or that the viewer may not read.
const gone = (org, main) => main.replaceChildren(emptyCard("No such artifact", "It was deleted, or it isn't shared with you.",
  h("a", { class: "btn", href: base + org.slug + "/artifacts", "data-nav": "" }, "Back to the artifacts")));

// showArtifact draws an artifact's page into main, with the version the page's query names, or its newest.
export async function showArtifact(org, main, can, id) {
  let a;
  try {
    a = await read(org, id);
  } catch (err) {
    if (err.status === 404 || err.status === 400) return gone(org, main);
    throw err;
  }
  knowTitle(a);
  const orgCrumb = { label: org.name, href: base + org.slug };
  recrumb(a.repository ? [orgCrumb, { label: a.repository.slug, href: base + org.slug + "/" + a.repository.slug },
    { label: "Artifacts", href: base + org.slug + "/" + a.repository.slug + "/artifacts" }, { label: a.title }]
    : [orgCrumb, { label: "Artifacts", href: base + org.slug + "/artifacts" }, { label: a.title }]);
  remember(org, "artifacts", { key: a.id, label: a.title, href: artifactHref(org, a), code: true, icon: "file" });
  const asked = Number(new URLSearchParams(location.search).get("version")) || 0;
  const path = "/orgs/" + org.slug + "/artifacts/" + a.id;
  let v;
  try {
    v = await api("GET", path + "/versions/" + asked);
  } catch (err) {
    if (err.status === 404 && asked) return go(pathOf(org, a), true);
    throw err;
  }
  const [list, who] = await Promise.all([api("GET", path + "/versions").then((d) => d.versions), api("GET", path + "/access")]);
  const refresh = (newest) => (newest && asked ? go(pathOf(org, a)) : showArtifact(org, main, can, a.id));
  const manage = a.permissions.includes("artifacts.manage");
  const share = () => people(org).then((p) => shareDialog(org, a, who, p, refresh));
  const actions = [manage ? h("button", { class: "btn", type: "button", onclick: share }, icon("users"), "Share") : null,
    h("a", { class: "btn", href: rawHref(org, a, v.number, true), download: "" }, icon("external-link"), "Download"),
    a.permissions.includes("artifacts.write") ? h("button", { class: "btn btn-primary", type: "button", onclick: () => editDialog(org, a, v, refresh) }, icon("pencil"), "Edit") : null];
  const header = h("header", { class: "page-header artifact-header" }, h("div", { class: "page-header-text" },
    h("div", { class: "app-page-heading-title artifact-heading" }, icon(kinds[a.kind].icon), h("h1", { class: "page-header-title" }, a.title),
      h("span", { class: "tag" }, kinds[a.kind].word), reachBadge(a)),
    h("p", { class: "page-header-description artifact-origin", title: origin(a, v.number) }, origin(a, v.number))), h("div", { class: "page-header-actions" }, actions));
  const older = v.number !== a.head ? banner("info", null, "This is version " + v.number + ". The artifact shows version " + a.head + ".",
    h("a", { class: "btn btn-ghost btn-sm", href: artifactHref(org, a), "data-nav": "" }, "Show the newest")) : null;
  main.replaceChildren(...[header, older, h("div", { class: "artifact-columns" }, h("div", { class: "artifact-main" }, body(org, a, v)),
    h("div", { class: "artifact-side" }, about(a), access(org, a, who, manage, share, () => refresh()), versions(org, a, list, v.number)))].filter(Boolean));
}
