// An artifact's own page (Figma "Artifact"), at /<org>/artifacts/<id>: its title, kind, widest audience and where it
// came from; Share, Download and Edit as the viewer's permissions on it allow; the version shown, the newest unless
// the page's query names another, drawn so that it runs nothing in the Console's origin; and beside it what it is, who
// reaches it and its versions.

